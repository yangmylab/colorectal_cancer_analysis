#!/usr/bin/env Rscript
# 14_collect_plots.R
# Copy/generate the final figure set as plot_1, plot_2, ... with a manifest.

suppressPackageStartupMessages({
  library(data.table)
  library(ggplot2)
  library(yaml)
})

source("06_Analysis/1_R/1_Rscripts/utils.R")
cfg <- yaml::read_yaml("config/pipeline_config.yaml")
outdir <- "09_Figures/plots"
dir.create(outdir, recursive = TRUE, showWarnings = FALSE)

manifest <- list()
add_plot <- function(n, src, desc) {
  manifest[[length(manifest) + 1]] <<- data.frame(plot = paste0("plot_", n), source = src, description = desc)
}
copy_pair <- function(src_base, n, desc) {
  for (ext in c("pdf", "jpg")) {
    src <- paste0(src_base, ".", ext)
    dst <- file.path(outdir, sprintf("plot_%d.%s", n, ext))
    if (!file.exists(src)) next
    # the multi-omic layers are written directly to outdir, so src and dst can be the same file
    if (normalizePath(src, mustWork = FALSE) != normalizePath(dst, mustWork = FALSE)) {
      file.copy(src, dst, overwrite = TRUE)
    }
  }
  add_plot(n, src_base, desc)
}

# 1. Single-cell marker signatures (already generated by the Python script)
add_plot(1, "06_Analysis/09_SingleCell/celltype_signature_symbols.tsv; 09_Figures/plots/plot_1", "GSE132465 single-cell marker signatures")

# 2-5 QC
copy_pair("05_QC/Figures/01_pca_uncorrected", 2, "QC PCA, uncorrected")
copy_pair("05_QC/Figures/01_pca_batch_corrected", 3, "QC PCA, batch-corrected")
copy_pair("05_QC/Figures/01_library_size", 4, "Library size by group")
copy_pair("05_QC/Figures/01_top_variable_heatmap", 5, "Top 500 variable features")

# 6-8 signatures and ecotypes
copy_pair("06_Analysis/05_Immune_Analysis/02_signature_heatmap", 6, "Hallmark signature heatmap")
copy_pair("06_Analysis/03_Clustering/03_consensus_heatmap", 7, "Consensus matrix for selected K")
copy_pair("06_Analysis/03_Clustering/03_ecotype_pca", 8, "SNF ecotype PCA")

# 9-12 clinical and stability
copy_pair("09_Figures/Figure_1_stability", 9, "Ecotype stability across K")
copy_pair("09_Figures/Figure_2_km", 10, "Kaplan-Meier by ecotype")
copy_pair("06_Analysis/06_Other_Analysis/04_calibration_5y", 11, "5-year calibration")
copy_pair("06_Analysis/06_Other_Analysis/04_dca_5y", 12, "5-year decision curve")

# 13. Deconvolution fractions
sig <- readRDS(file.path(cfg$paths$processed, "signature_scores.rds"))
if (!is.null(sig$deconv)) {
  frac <- rowMeans(sig$deconv, na.rm = TRUE)
  df <- data.frame(cell_type = names(frac), fraction = as.numeric(frac))
  save_plot(function() {
    print(ggplot(df, aes(reorder(cell_type, -fraction), fraction, fill = cell_type)) + geom_col() + theme_bw() + theme(axis.text.x = element_text(angle = 45, hjust = 1), legend.position = "none") + labs(x = NULL, y = "Mean fraction", title = "TCGA deconvolution fractions"))
  }, file.path(outdir, "plot_13"), 7, 4)
  add_plot(13, "signature_scores.rds$deconv", "Mean TCGA cell-type fractions")
}

# 14. K sensitivity
ks <- fread("08_Robustness/K_sensitivity.tsv", data.table = FALSE)
if (nrow(ks) > 0) {
  save_plot(function() {
    print(ggplot(ks, aes(K, c_index_full)) + geom_line() + geom_point(size = 2) + geom_hline(yintercept = ks$c_index_base[1], linetype = 2) + geom_text(aes(label = paste0("p=", signif(lrt_p, 2))), vjust = -0.8, size = 3) + theme_bw() + labs(x = "K", y = "C-index (full model)", title = "K sensitivity"))
  }, file.path(outdir, "plot_14"), 6, 4)
  add_plot(14, "08_Robustness/K_sensitivity.tsv", "K sensitivity of the survival model")
}

# 15. Validation forest plot
val <- fread("06_Analysis/06_Other_Analysis/validation_performance.tsv", data.table = FALSE)
val <- val[val$cohort != "none", , drop = FALSE]
if (nrow(val) > 0) {
  val$se <- abs(log(val$hr)) / qnorm(1 - val$p_hr / 2)
  val$lower <- exp(log(val$hr) - 1.96 * val$se)
  val$upper <- exp(log(val$hr) + 1.96 * val$se)
  meta <- fread("07_Validation/validation_meta_analysis.tsv", data.table = FALSE)
  forest <- data.frame(cohort = c(val$cohort, "Meta (fixed)"), HR = c(val$hr, meta$HR[1]), lower = c(val$lower, meta$lower[1]), upper = c(val$upper, meta$upper[1]), p = c(val$p_hr, meta$p[1]))
  save_plot(function() {
    print(ggplot(forest, aes(x = HR, y = reorder(cohort, HR))) + geom_vline(xintercept = 1, linetype = 2) + geom_pointrange(aes(xmin = lower, xmax = upper)) + theme_bw() + labs(x = "Hazard ratio (E2 vs E1)", y = NULL, title = "External validation"))
  }, file.path(outdir, "plot_15"), 7, 4)
  add_plot(15, "validation_performance.tsv + validation_meta_analysis.tsv", "Validation forest plot")
}

# 16-24. Multi-omics layers (proteomics, methylation) — copied if present
